from ecd_epitope_scanner.joint_design_v4 import sectors as module
from ecd_epitope_scanner.joint_design_v4.models import EpitopeEvidence, ResidueKey, SurfaceEvidence
from ecd_epitope_scanner.models import ResidueRecord


@pytest.fixture
def ctla4():
    saved = json.loads((Path(__file__).parent / "fixtures/ctla4_small_partition.json").read_text(encoding="utf-8"))
    records = {row["uniprot_pos"]: ResidueRecord(**row) for row in saved["records"]}
    graph = {position: {} for position in records}
    for left, right, distance in saved["edges"]:
        graph[left][right] = graph[right][left] = distance
    surface = [SurfaceEvidence(**(row | {"residue": ResidueKey(**row["residue"])})) for row in saved["surface"]]
    epitope = [EpitopeEvidence(**(row | {"residue": ResidueKey(**row["residue"])})) for row in saved["epitope"]]
    return saved, surface, epitope, graph, records


def assert_partition(result, surface, graph, records, geo=26.0, ca=18.0):
    assigned = [position for region in result for position in region.residue_positions]
    assert len(assigned) == len(set(assigned))
    assert set(assigned) == set(graph)
    areas = {row.residue.uniprot_pos: row.mapped_surface_area_a2 for row in surface}
    for region in result:
        group = set(region.residue_positions)
        assert len(group) >= 4
        assert sum(areas[position] for position in group) >= 50
        assert set(module._distance(graph, min(group), group)) == group
        # Recompute from raw coordinates/distances, not rounded sector summaries.
        for left in group:
            distances = module._distance(graph, left, set(graph))
            for right in group:
                assert distances[right] <= geo
                assert np.linalg.norm(np.asarray(records[left].ca) - records[right].ca) <= ca
        assert not {"SMALL_DISPLAY_REGION", "LOW_SURFACE_AREA", "DISCONNECTED_SECTOR",
                    "GEODESIC_DIAMETER_EXCEEDED", "EUCLIDEAN_DIAMETER_EXCEEDED"} & set(region.quality_flags)


def line_inputs(count, area=20.0):
    records = {position: ResidueRecord(position, "A", "A", position, ca=(float(position), 0, 0))
               for position in range(1, count + 1)}
    graph = {position: {} for position in records}
    for position in range(1, count):
        graph[position][position + 1] = graph[position + 1][position] = 1.0
    surface = [SurfaceEvidence(ResidueKey("0", "A", position, uniprot_pos=position),
                               mapped_surface_area_a2=area) for position in records]
    return surface, [], graph, records


def test_saved_ctla4_repairs_to_nine_valid_regions(ctla4):
    saved, surface, epitope, graph, records = ctla4
    diagnostics = {}
    result = module.build_epitope_sectors(surface, epitope, graph, records, diagnostics=diagnostics)
    assert len(graph) == 71
    # Region IDs are regenerated by minimum position, so moved boundary nodes
    # can change their order relative to the historical labels.
    assert sorted(len(region.residue_positions) for region in result) == sorted([12, 5, 13, 9, 9, 9, 4, 4, 6])
    assert_partition(result, surface, graph, records)
    assert diagnostics["status"] == "COMPLETE"
    assert diagnostics["version"] == "connected_bounded_v3"
    assert any(repair["boundary_moves"] for repair in diagnostics["repairs"])
    assert saved["provenance"]["structure_type"] == "experimental"
    assert saved["provenance"]["author_chain"] == "A"


def test_ctla4_singleton_uses_nearest_region_and_adjusts_boundary(ctla4):
    saved, surface, epitope, graph, records = ctla4
    diagnostics = {}
    module.build_epitope_sectors(surface, epitope, graph, records, diagnostics=diagnostics)
    singleton_repair = next(repair for repair in diagnostics["repairs"] if repair["source_positions"] == [106])
    distances = module._distance(graph, 106, set(graph))
    candidates = [group for group in saved["original_groups"] if 106 not in group
                  and any(position in graph[106] for position in group)]
    nearest = min(candidates, key=lambda group: (min(distances[position] for position in group), min(group)))
    assert singleton_repair["target_positions_before"] == nearest
    assert singleton_repair["boundary_moves"]
    assert 106 in singleton_repair["target_positions_after"]


def test_saved_ctla4_is_invariant_to_input_order(ctla4):
    _, surface, epitope, graph, records = ctla4
    first_diagnostics, reversed_diagnostics = {}, {}
    first = module.build_epitope_sectors(surface, epitope, graph, records, diagnostics=first_diagnostics)
    reversed_graph = {position: dict(reversed(list(neighbors.items())))
                      for position, neighbors in reversed(list(graph.items()))}
    second = module.build_epitope_sectors(list(reversed(surface)), list(reversed(epitope)), reversed_graph,
                                         dict(reversed(list(records.items()))), diagnostics=reversed_diagnostics)
    assert first == second
    assert first_diagnostics == reversed_diagnostics


def test_ctla4_uses_next_nearest_when_closest_cannot_be_repaired(ctla4):
    saved, surface, epitope, graph, records = ctla4
    diagnostics = {}
    module.build_epitope_sectors(surface, epitope, graph, records, diagnostics=diagnostics)
    repair = next(row for row in diagnostics["repairs"] if row["source_positions"] == [92, 93])
    source = {92, 93}
    distances = {position: module._distance(graph, position, set(graph)) for position in source}
    candidates = [group for group in saved["original_groups"] if not source & set(group)
                  and any(neighbor in group for position in source for neighbor in graph[position])]
    nearest = min(candidates, key=lambda group: (
        min(distances[position][neighbor] for position in source for neighbor in group), min(group)))
    assert 98 in nearest  # VS006 is closest, but its displaced nodes have no legal reassignment.
    assert repair["target_positions_before"] != nearest
    assert 67 in repair["target_positions_before"]
    assert repair["boundary_moves"]


def test_small_region_directly_merges_without_boundary_search(monkeypatch):
    inputs = line_inputs(7)
    monkeypatch.setattr(module, "PARTITION_SEARCH_LIMIT", 0)
    result = module.build_epitope_sectors(*inputs, max_sectors=2)
    assert [region.residue_positions for region in result] == [list(range(1, 8))]
    assert_partition(result, inputs[0], inputs[2], inputs[3])


def test_boundary_rebuild_preserves_valid_target_remainder():
    surface, epitope, graph, records = line_inputs(13)
    for position, record in records.items():
        record.ca = (position * 3.8, 0, 0)
        graph[position] = {neighbor: 3.8 for neighbor in graph[position]}
    diagnostics = {}
    result = module.build_epitope_sectors(surface, epitope, graph, records,
                                        max_sectors=1, diagnostics=diagnostics)
    assert_partition(result, surface, graph, records)
    assert [region.residue_positions for region in result] == [
        list(range(1, 6)), list(range(6, 10)), list(range(10, 14))]
    repair = next(row for row in diagnostics["repairs"] if row["repair_type"] == "BOUNDARY_REBUILD")
    assert repair["source_positions"] == [11, 12, 13]
    assert repair["target_positions_before"] == [6, 7, 8, 9, 10]
    # Full absorption strands nodes 6–8; rebuilding only the shared boundary
    # leaves the donor connected and above both minimums instead.
    assert repair["target_positions_after"] == [10, 11, 12, 13]
    reversed_diagnostics = {}
    reversed_graph = {position: dict(reversed(list(neighbors.items())))
                      for position, neighbors in reversed(list(graph.items()))}
    repeated = module.build_epitope_sectors(list(reversed(surface)), epitope, reversed_graph,
                                          records, max_sectors=1, diagnostics=reversed_diagnostics)
    assert repeated == result
    assert reversed_diagnostics == diagnostics


@pytest.mark.parametrize("count,area", [(3, 20.0), (8, 5.0)])
def test_unsatisfied_minimum_is_explicit_failure(count, area):
    inputs = line_inputs(count, area)
    diagnostics = {}
    with pytest.raises(module.PartitionConstraintError) as captured:
        module.build_epitope_sectors(*inputs, max_sectors=1, diagnostics=diagnostics)
    assert captured.value.diagnostics == diagnostics
    assert diagnostics["status"] == "FAILED"
    assert diagnostics["reason"] == "UNSATISFIED_PARTITION_CONSTRAINTS"
    assert diagnostics["draft_regions"]


def test_small_disconnected_component_cannot_be_hidden_by_other_regions():
    surface, epitope, graph, records = line_inputs(8)
    del graph[3][4]
    del graph[4][3]
    with pytest.raises(module.PartitionConstraintError):
        module.build_epitope_sectors(surface, epitope, graph, records, max_sectors=2)


def test_search_exhaustion_reports_unknown_not_no_solution(ctla4, monkeypatch):
    _, surface, epitope, graph, records = ctla4
    graph_before = {position: dict(neighbors) for position, neighbors in graph.items()}
    monkeypatch.setattr(module, "PARTITION_SEARCH_LIMIT", 0)
    diagnostics = {}
    with pytest.raises(module.PartitionConstraintError) as captured:
        module.build_epitope_sectors(surface, epitope, graph, records, diagnostics=diagnostics)
    assert captured.value.diagnostics == diagnostics
    assert diagnostics["reason"] == "SEARCH_BUDGET_EXHAUSTED"
    assert diagnostics["status"] == "FAILED"
    assert diagnostics["draft_regions"]
    assert graph == graph_before
